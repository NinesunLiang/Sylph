/// 把 [PoseStroke] 画出来（矢量火柴人）。
class PoseFigurePainter extends CustomPainter {
  PoseFigurePainter({
    required this.pose,
    required this.color,
    this.strokeWidth = 2.4,
    this.drawGround = true,
  });

  final Pose pose;
  final Color color;
  final double strokeWidth;
  final bool drawGround;

  @override
  void paint(Canvas canvas, Size size) {
    // 🔴 参考照姿势没有火柴人线条（`strokes` 为空），它们靠 `imagePath` 显示照片。
    // 空列表取 `.first` 会抛 `Bad state: No element`，真机上表现为
    // 「摄影助手屡次停止运行」。
    //
    // 触发路径：姿势集 → 参考照 → 点开一张 → 「送到预览页，照着摆」
    // → 预览页用本画笔把这个姿势叠到实时预览上 → 崩。
    //
    // 老的 31 个火柴人姿势都有线条，所以这条路径一直没暴露；
    // 一旦库里出现"有照片、无线条"的姿势就必崩。
    // 没有线条就什么都不画（照片由调用方的 Image 负责），直接返回。
    if (pose.strokes.isEmpty) return;

    final paint = Paint()
      ..color = color
      ..strokeWidth = strokeWidth
      ..strokeCap = StrokeCap.round
      ..style = PaintingStyle.stroke;

    // 留边距：坐标本身在 0.10–0.94，直接乘会几乎贴到上下边，
    // 视觉上像"人形的脚伸进了下面的标题框"（浏览器实测截图被我看成 bug）。
    // 这里把绘制区域**内缩**，四周留出呼吸空间。
    // 注意线条有 strokeWidth，不内缩的话半条线会画出边界。
    const insetX = 0.06, insetY = 0.04, insetStroke = 0.01;
    final sx = size.width * (1 - 2 * (insetX + insetStroke));
    final sy = size.height * (1 - 2 * (insetY + insetStroke));
    final ox = size.width * (insetX + insetStroke);
    final oy = size.height * (insetY + insetStroke);

    Offset p(double x, double y) => Offset(ox + x * sx, oy + y * sy);

    // 头（圆形）
    final headCenter = p(pose.strokes.first.x1, pose.strokes.first.y1);
    canvas.drawCircle(headCenter, size.shortestSide * 0.055, paint);

    for (final s in pose.strokes) {
      final a = p(s.x1, s.y1);
      final b = p(s.x2, s.y2);
      if (s.curve == 0) {
        canvas.drawLine(a, b, paint);
      } else {
        final mid = Offset((a.dx + b.dx) / 2, (a.dy + b.dy) / 2);
        final ctrl = Offset(mid.dx + s.curve * size.width, mid.dy);
        final path = Path()
          ..moveTo(a.dx, a.dy)
          ..quadraticBezierTo(ctrl.dx, ctrl.dy, b.dx, b.dy);
        canvas.drawPath(path, paint);
      }
    }

    if (drawGround) {
      final ground = Paint()
        ..color = color.withValues(alpha: 0.35)
        ..strokeWidth = 1;
      canvas.drawLine(
        Offset(size.width * 0.15, size.height * 0.94),
        Offset(size.width * 0.85, size.height * 0.94),
        ground,
      );
    }
  }

  @override
  bool shouldRepaint(covariant PoseFigurePainter old) =>
      old.pose != pose || old.color != color;
}
