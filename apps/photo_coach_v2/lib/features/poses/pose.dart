import 'package:flutter/material.dart';

/// 姿势条目。
///
/// 素材策略：当前库是**真实参考照片**（[imagePath]，assets/poses/ 下）。
/// 早 v0 曾用代码画的矢量火柴人线条（[strokes]）起步，v0.4.0 起火柴人库
/// 已删除（用户要求只留真实参考照）；[strokes] 字段保留，参考照姿势全传
/// 空列表，[PoseFigurePainter] 靠「空列表不画不崩」的防御分支兜底。
class Pose {
  const Pose({
    required this.id,
    required this.title,
    required this.category,
    required this.strokes,
    this.tips = const [],
    this.imagePath,
    this.scene = '',
    this.tags = const [],
    this.gender = '',
    this.posture = '',
    this.guidance,
  });

  final String id;
  final String title;

  /// 分类：站姿 / 半身 / 坐姿 / 全身 / 双人 / 亲子 / 动态 / 细节
  final String category;

  /// 火柴人线条，坐标 0–1，与画布尺寸无关。
  ///
  /// 用真实参考照的姿势可以留空（这时 UI 必须走 [imagePath]）。
  final List<PoseStroke> strokes;

  /// 拍摄要点。
  final List<String> tips;

  /// 真实参考照（assets/poses/xxx.jpg）。为空才用 [strokes] 画。
  final String? imagePath;

  /// 适合什么场景（街拍/室内/海边/棚拍…）。
  final String scene;

  /// 额外检索词（同义词、别名），让搜索更宽容。
  final List<String> tags;

  /// 一级分类：性別（女 / 男）。火柴人姿势为空字符串。
  final String gender;

  /// 二级分类：姿态（站 / 坐 / 躺）。火柴人姿势为空字符串。
  final String posture;

  /// 真实参考照的拍摄指导。点开图翻面看的就是它。
  final PoseGuidance? guidance;

  /// 是不是真实参考照（不是代码画的火柴人）。
  bool get hasPhoto => imagePath != null && imagePath!.isNotEmpty;
}

/// 一条线：从 (x1,y1) 到 (x2,y2)，可以带曲率。
class PoseStroke {
  const PoseStroke(this.x1, this.y1, this.x2, this.y2, {this.curve = 0});

  final double x1;
  final double y1;
  final double x2;
  final double y2;

  /// 0 = 直线；非 0 = 二次贝塞尔的控制点偏移量（相对中点）。
  final double curve;
}

/// 一张真实参考照的拍摄指导。点开图**翻面**看到的就是这些。
///
/// 为什么单独一个类而不是塞进 Pose 的字段：这些是「怎么拍」而不是
/// 「哪个姿势」，混在一起 Pose 会变成 12 个字段的数据袋。
class PoseGuidance {
  const PoseGuidance({
    required this.cameraHeight,
    required this.direction,
    required this.framing,
    required this.action,
    required this.expression,
    required this.why,
  });

  /// 机位高低：低机位 / 平机位 / 高机位
  final String cameraHeight;

  /// 人物朝向：正面 / 四分之三侧 / 正侧面 / 背面 / 背影回头
  final String direction;

  /// 景别：全身 / 七分身 / 半身
  final String framing;

  /// 动作：手和腿具体怎么放
  final String action;

  /// 表情与视线
  final String expression;

  /// 这张为什么好看（用了什么视觉手法）
  final String why;
}

/// 姿势目录。v0.4.0 起 App 内只发真实参考照库（见 [photoPoses]）；
/// 火柴人库已删除（[builtIn] 为空列表，仅留接口）。
class PoseCatalog {
  const PoseCatalog();

  // v0.4.0：火柴人姿势库（原 31 个代码绘制姿势）按用户要求删除。
  // App 内姿势库只剩真实参考照（顶层 const [photoPoses]，
  // 由 .work/poses/gen_dart.py 生成，250 张，带授权文档）。
  //
  // 保留的东西（别删）：
  // · Pose.strokes 字段 —— 参考照全传空列表，模型不能改；
  // · [PoseFigurePainter] —— 预览叠加层的防御分支还用（空 strokes 不画不崩）；
  // · categories / byCategory / search 方法 —— 对空列表恒为空结果，保留避免破坏调用面。
  static const List<Pose> builtIn = [];

  static List<String> get categories =>
      ['全部', ...{for (final p in builtIn) p.category}];

  static List<Pose> byCategory(String category) => category == '全部'
      ? builtIn
      : builtIn.where((p) => p.category == category).toList();

  static List<Pose> search(String query) => _match(builtIn, query);

  // ── 真实参考照：一级性別 → 二级姿态 ───────────────────────────────

  /// 一级分类：性別。哪个性別有图才会出现。
  static List<String> get genders =>
      ['全部', ...{for (final p in photoPoses) p.gender}.where((g) => g.isNotEmpty)];

  /// 某个性別下的二级分类：姿态。
  ///
  /// 女：站 / 坐 / 躺。男：站 / 坐（没有躺的素材）。
  static List<String> posturesOf(String gender) => [
        '全部',
        ...{
          for (final p in photoPoses)
            if (gender == '全部' || p.gender == gender) p.posture
        }.where((s) => s.isNotEmpty),
      ];

  /// 按 性別 + 姿态 筛参考照。两者都可以传「全部」。
  static List<Pose> photos({String gender = '全部', String posture = '全部'}) =>
      photoPoses.where((p) {
        if (gender != '全部' && p.gender != gender) return false;
        if (posture != '全部' && p.posture != posture) return false;
        return true;
      }).toList();

  /// 参考照搜索（标题 / 姿态 / 指导文案都搜）。
  static List<Pose> searchPhotos(String query) => _match(photoPoses, query);

  static List<Pose> _match(List<Pose> src, String query) {
    final q = query.trim().toLowerCase();
    if (q.isEmpty) return src;
    return src
        .where((p) =>
            p.title.toLowerCase().contains(q) ||
            p.category.toLowerCase().contains(q) ||
            p.scene.toLowerCase().contains(q) ||
            p.posture.toLowerCase().contains(q) ||
            p.tags.any((t) => t.toLowerCase().contains(q)) ||
            p.tips.any((t) => t.toLowerCase().contains(q)) ||
            (p.guidance?.action.toLowerCase().contains(q) ?? false) ||
            (p.guidance?.expression.toLowerCase().contains(q) ?? false) ||
            (p.guidance?.why.toLowerCase().contains(q) ?? false))
        .toList();
  }
}

